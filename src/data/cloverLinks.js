const slugify = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// A Clover item page needs only the item's id; the name in the link is just for show.
// The list above comes straight from Clover so it wins; a Clover photo's address carries the id for drinks missing from it
// (photos can go stale if a drink is recreated in Clover).
function cloverItemUrl(item) {
    const slug = slugify(item.name);
    const id = CLOVER_ITEM_IDS[slug] ?? item.image?.match(/cloverstatic\.com\/menu-assets\/items\/([A-Z0-9]+)_/)?.[1];
    return id ? `${CLOVER_SITE}/menu/${slug}-${id}` : `${CLOVER_SITE}/menu/all`;
}

export const openCloverItem = (item) => window.open(cloverItemUrl(item), "_blank", "noopener");
